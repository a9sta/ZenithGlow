/** 허리값(가운데 여섯 토막 중 가장 얇은 곳 ÷ 가장 두꺼운 곳, %)을 말로 */
export function waistWord(a) {
  if (a < 20) return '가운데가 거의 끊어질 만큼 가늘다';
  if (a < 35) return '가운데가 목처럼 가늘게 이어진다';
  if (a < 47) return '가운데가 뚜렷하게 잘록하다';
  if (a < 60) return '가운데가 약간 잘록하다';
  if (a < 72) return '가운데가 꽤 두툼하다';
  if (a < 84) return '가운데가 불룩하게 찼다';
  return '가운데가 꽉 차서 잘록한 데가 없다';
}
/** 가장 두꺼운 토막의 몫(%)을 말로 */
export function bigWord(b) {
  if (b < 12) return '열 토막의 폭이 거의 같다';
  if (b < 14) return '가장 두꺼운 토막도 평균에서 조금 벗어날 뿐이다';
  if (b < 17) return '가장 두꺼운 토막이 평균의 한 배 반쯤이다';
  if (b < 22) return '가장 두꺼운 토막이 평균의 두 배 가까이 부풀었다';
  if (b < 32) return '한 토막에 땅의 4분의 1 안팎이 몰려 있다';
  return '한 토막에 땅의 3분의 1 넘게 몰려 있다';
}
/** 앞 세 토막과 뒤 세 토막의 차이를 말로 */
export function leanWord(f0, f2) {
  const d = f0 - f2;
  if (Math.abs(d) < 3) return '앞뒤가 비슷하게 나뉘어 있다';
  return d > 0 ? '앞쪽으로 기울어 있다' : '뒤쪽으로 기울어 있다';
}
/** 두 허리값을 견준 말 */
export function cmpWord(x, y) {
  const d = x - y;
  if (Math.abs(d) < 3) return '거의 같은 수준이다';
  return d > 0 ? '그보다 가운데가 더 찬 쪽이다' : '그보다 가운데가 더 잘록한 쪽이다';
}

